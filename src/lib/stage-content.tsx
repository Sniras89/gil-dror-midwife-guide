function repeatCardsForStage(id: number, base: ContentCard[]): ContentCard[] {
  if (id === 2) {
    return [
      repeatStage2Top,
      cervicalCard,
      repeatCervicalCard,
      ...base.filter(
        (c) =>
          c !== cervicalCard &&
          c !== activeTransitionCard &&
          c.title !== "מושגי יסוד: שינויים בצוואר הרחם",
      ),
      activeTransitionCard,
    ];
  }
  if (id === 3) {
    return [base[0], goldenRuleCard, ...base.slice(1), ...(repeatExtraCards[3] ?? [])];
  }
  const extra = repeatExtraCards[id];
  return extra?.length ? [...base, ...extra] : base;
}

export function getStageContent(birthType: BirthType): Record<number, StageContent> {
  const result: Record<number, StageContent> = {};
  for (const key of Object.keys(stageContent)) {
    const id = Number(key);
    const base = stageContent[id];
    result[id] = {
      cards: birthType === "repeat" ? repeatCardsForStage(id, base.cards) : base.cards,
      extra: id === 3 ? <UrgencyCalculator birthType={birthType} /> : base.extra,
    };
  }
  return result;
}
